function cataloguePhrases() {
  return Object.fromEntries(Object.entries(translations.en).map(([key, english]) => [english, translations.te[key]]));
}

const phraseMap = { ...cataloguePhrases(), ...teluguPhrases, ...commonLabels, ...remainingTeluguPhrases };
const normalizedMap = new Map(Object.entries(phraseMap).map(([english, telugu]) => [english.trim().toLocaleLowerCase('en'), telugu]));

export function translateUiText(language, value) {
  if (language !== 'te' || typeof value !== 'string' || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  const text = value.trim();
  const translated = phraseMap[text] || normalizedMap.get(text.toLocaleLowerCase('en'));
  if (translated) return `${leading}${translated}${trailing}`;
  return value;
}

export function translateUiNode(language, node) {
  if (typeof node === 'string') return translateUiText(language, node);
  if (Array.isArray(node)) return node.map((child) => translateUiNode(language, child));
  return node;
}

